function getDisplayTitle(url) {
  const slug = url.replace(/^https?:\/\/[^/]+\/[^/]+\//, '').replace(/\/$/, '');
  return DISPLAY_TITLES[slug] || slug.replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
}

